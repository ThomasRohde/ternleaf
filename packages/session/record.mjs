// The change record of a document: every change that the author accepted,
// with the request, the reason and the author's note. It is written for a
// reader who was not there, for example a reviewer or an approver.
const line = text => String(text ?? "").replace(/\s+/g, " ").trim();
const quote = text => "> " + (line(text) || "(nothing)");
const count = (number, word) => `${number} ${word}${number === 1 ? "" : "s"}`;

// One accepted change, under a heading of the given level.
function entry(out, change, heading) {
  out.push(`${heading} Revision ${change.revision}`, "",
    change.origin === "word" ? `- Source: ${line(change.prompt)}`
      : `- Request (${change.origin === "chat" ? "from the chat" : "from the canvas"}): ${line(change.prompt)}`);
  if (change.rationale) out.push(`- Copilot's reason: ${line(change.rationale)}`);
  if (change.note) out.push(`- Author's note: ${line(change.note)}`);
  out.push("", "Before:", "", quote(change.before), "", "After:", "", quote(change.replacement), "");
}

export function changeRecord({ document, revision, changes, when = new Date() }) {
  const out = [`# Change record: ${document}`, "",
    `Revision ${revision}, written ${when.toISOString().slice(0, 10)}. ${changes.length} accepted ${changes.length === 1 ? "change" : "changes"}.`,
    "", "The author accepted each change below. A change that is not in this record was typed by the author.", ""];
  for (const [index, change] of changes.entries()) entry(out, change, `## ${index + 1}.`);
  return out.join("\n");
}

// The change log that travels with the document in git, next to it as
// <file>.docx.changes.md. Each save to the file adds one section at the end
// with the changes that the author accepted since the save before.
export const changeLogNotice = document =>
  `<!-- Ternleaf adds a section to this file each time the author saves ${line(document)}. Do not edit this file. -->`;

export function changeLog({ document, existing = "", revision, changes, when = new Date() }) {
  const out = existing.trim()
    ? [existing.replace(/\s+$/, ""), ""]
    : [changeLogNotice(document), "", `# Change log: ${document}`, "",
      "Each section is one save to the Word file. The author accepted each change in it. A change that is not in this log was typed by the author.", ""];
  const stamp = when.toISOString();
  out.push(`## Saved ${stamp.slice(0, 10)} ${stamp.slice(11, 16)} UTC: ${count(revision, "revision")}, ${count(changes.length, "accepted change")}`, "");
  if (!changes.length) out.push("No accepted changes in this save.", "");
  for (const [index, change] of changes.entries()) entry(out, change, `### ${index + 1}.`);
  return out.join("\n");
}

// The text copy of a document for diffs, next to it as <file>.docx.md.
export const textCopy = (document, markdown) =>
  `<!-- Ternleaf writes this file from ${line(document)} each time the author saves it. Do not edit this file: the next save replaces it. -->\n\n`
  + String(markdown).replace(/^﻿/, "").replace(/\s+$/, "") + "\n";

// A proposed git commit message for a save. Ternleaf does not run git: the
// author copies the message.
const clip = (text, length) => { const value = line(text); return value.length > length ? value.slice(0, length - 1) + "…" : value; };
export function commitMessage({ document, revision, changes, limit = 20 }) {
  const first = `Update ${document}: ${changes.length ? count(changes.length, "accepted change") : "no accepted changes"}`
    + (revision !== changes.length ? `, ${count(revision, "revision")}` : "");
  const body = changes.slice(0, limit).map(change => `- "${clip(change.before, 30)}" → `
    + (line(change.replacement) ? `"${clip(change.replacement, 30)}"` : "(removed)") + ` (revision ${change.revision})`);
  if (changes.length > limit) body.push(`- And ${count(changes.length - limit, "more accepted change")}.`);
  return [first, ...(body.length ? ["", ...body] : [])].join("\n");
}
